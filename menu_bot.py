def _map_font(s: str, font: str) -> str:
    A, a, d = _FONT_BASE[font]
    out = []
    for ch in s:
        if "A" <= ch <= "Z":
            out.append(chr(A + ord(ch) - 65))
        elif "a" <= ch <= "z":
            out.append(chr(a + ord(ch) - 97))
        elif "0" <= ch <= "9":
            out.append(chr(d + ord(ch) - 48))
        else:
            out.append(ch)
    return "".join(out)


def _deitalic(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\u210e":
            out.append("h")
        elif 0x1D44E <= o <= 0x1D467:
            out.append(chr(97 + o - 0x1D44E))
        elif 0x1D434 <= o <= 0x1D44D:
            out.append(chr(65 + o - 0x1D434))
        else:
            out.append(ch)
    return "".join(out)


def u16(s: str) -> int:
    return len(s.encode("utf-16-le")) // 2


