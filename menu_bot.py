@client.on(events.NewMessage(outgoing=True, pattern=r"^\+menu(\d{1,2})?$"))
async def menu_cmd(event):
    n = event.pattern_match.group(1)
    theme_no = int(n) if n else random.randint(1, len(NAMES))
    if theme_no not in NAMES:
        return await event.edit("Menu 1 se %d tak hi hai. +help se list dekh." % len(NAMES))
