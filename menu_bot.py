def split_in_two(text, ents):
    mid = len(text) // 2
    cut = text.rfind("\n\n", 0, mid + 400)
    if cut == -1:
        cut = text.find("\n", mid)
    a, b = text[:cut], text[cut:].lstrip("\n")
    cut_u = u16(a)
    skip = u16(text[cut:]) - u16(b)
    ea = [e for e in ents if e.offset < cut_u]
    eb = [MessageEntityCustomEmoji(offset=e.offset - cut_u - skip, length=e.length,
                                   document_id=e.document_id) for e in ents if e.offset >= cut_u]
    return (a, ea), (b, eb)


async def send_menu(event, text, ents):
    sent = []
    try:
        sent.append(await event.edit(text, formatting_entities=ents, parse_mode=None))
    except MessageTooLongError:
        (a, ea), (b, eb) = split_in_two(text, ents)
        sent.append(await event.edit(a, formatting_entities=ea, parse_mode=None))
        sent.append(await event.respond(b, formatting_entities=eb, parse_mode=None))
    await asyncio.sleep(AUTO_DELETE)
    for m in sent:
        try:
            await m.delete()
        except Exception:
            pass


